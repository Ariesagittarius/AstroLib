export interface FlatBook extends Book {
  collectionId: string;
  collectionSlug: string;
  collectionTitle: string;
}

export function getAllBooks(): FlatBook[] {
  const list: FlatBook[] = [];
  for (const col of collections) {
    for (const book of col.books) {
      list.push({
        ...book,
        collectionId: col.id,
        collectionSlug: col.slug,
        collectionTitle: col.title,
      });
    }
  }
  return list;
}
